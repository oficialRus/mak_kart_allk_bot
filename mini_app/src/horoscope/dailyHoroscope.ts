export type HoroscopeBlock = {
  emoji: string;
  name: string;
  /** Заголовок вида «♈️ Овен · 27 марта» */
  headline: string;
  text: string;
};

function calendarDayKey(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

/** Подпись даты для пользователя (локальный календарь устройства). */
export function formatHoroscopeDateLabel(d: Date): string {
  return d.toLocaleDateString("ru-RU", { day: "numeric", month: "long" });
}

/** Все 12 знаков с текстом на указанную дату (обычно `new Date()`). */
export function getDailyHoroscopeBlocks(forDate: Date = new Date()): HoroscopeBlock[] {
  const dayKey = calendarDayKey(forDate);
  const dateLabel = formatHoroscopeDateLabel(forDate);

  return ZODIAC_SIGNS.map((sign) => {
    const variants = TEXTS_BY_SIGN[sign.id] ?? ["Сегодня прислушайтесь к себе и двигайтесь в своём темпе."];
    const idx = hashDayKey(`${dayKey}|${sign.id}`) % variants.length;
    return {
      emoji: sign.emoji,
      name: sign.name,
      headline: `${sign.emoji} ${sign.name} · ${dateLabel}`,
      text: variants[idx] ?? variants[0],
    };
  });
}
