// BuildUserPrompt формирует пользовательский промпт для выбранной цифры.
func BuildUserPrompt(num int, p DigitParams) string {
	return "Сгенерируй мотивационное послание дня.\n\n" +
		"Цифра дня: " + itoa(num) + "\n\n" +
		"Тема: " + p.Theme + "\n" +
		"Фокус: " + p.Focus + "\n" +
		"Эмоция: " + p.Emotion + "\n" +
		"Действие: " + p.Action + "\n" +
		"Энергия дня: " + p.Energy + "\n"
}

// маленький локальный itoa, чтобы не тянуть strconv во все импорты.
func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	neg := false
	if n < 0 {
		neg = true
		n = -n
	}
	buf := [12]byte{}
	i := len(buf)
	for n > 0 {
		i--
		buf[i] = byte('0' + (n % 10))
		n /= 10
	}
	if neg {
		i--
		buf[i] = '-'
	}
	return string(buf[i:])
}
